// Run manually with Node 22+: node --experimental-strip-types scripts/sync-previews.mjs
// Downloads only the catalog's texture files; never run as part of export or build.
import { Buffer } from 'node:buffer';
import { log } from 'node:console';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { unzipSync } from 'fflate';
import { catalog } from '../src/domain.ts';

const root = new URL('../', import.meta.url);
const javaClient = 'https://piston-data.mojang.com/v1/objects/e877b6a07acd633fb3bb475002175cec036e7b87/client.jar';
const bedrockRevision = '46ba6ea985fb5a92d79a9419198f10dda14c199d';
const sources = {
  java: {
    gameVersion: '26.3',
    metadataUrl: 'https://piston-meta.mojang.com/v1/packages/61fff1316bd50312624a858bbb5eb18fa45208ed/26.3.json',
    archiveUrl: javaClient,
    archiveSha1: 'e877b6a07acd633fb3bb475002175cec036e7b87',
  },
  bedrock: {
    gameVersion: '26.50', sampleVersion: '1.26.50.4', revision: bedrockRevision,
    repositoryUrl: `https://github.com/Mojang/bedrock-samples/tree/${bedrockRevision}/resource_pack`,
    licenseUrl: `https://github.com/Mojang/bedrock-samples/blob/${bedrockRevision}/LICENSE.md`,
  },
};
async function bytes(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return new Uint8Array(await response.arrayBuffer());
}
const clientBytes = await bytes(javaClient);
if (createHash('sha1').update(clientBytes).digest('hex') !== sources.java.archiveSha1) throw new Error('Java client hash mismatch');
const wanted = new Set(catalog('java').filter(a => a.kind === 'texture').map(a => `assets/minecraft/${a.path}`));
// Decompress only catalog PNGs. The game archive stays in memory.
const javaFiles = unzipSync(clientBytes, { filter: entry => wanted.has(entry.name) });
const textures = [];
// Opaque/carried PNG variants are official vanilla display references for these
// blocks; the replaceable Bedrock base files use TGA and are not browser images.
const bedrockDisplayVariants = {
  'textures/blocks/grass_side.png': 'textures/blocks/grass_side_carried.png',
  'textures/blocks/leaves_oak.png': 'textures/blocks/leaves_oak_opaque.png',
  'textures/blocks/door_oak_lower.png': 'textures/blocks/door_wood_lower.png',
  'textures/blocks/furnace_front.png': 'textures/blocks/furnace_front_off.png',
};
for (const edition of ['java', 'bedrock']) {
  const gameVersion = sources[edition].gameVersion;
  const folder = new URL(`public/previews/${edition}-${gameVersion}/`, root);
  await mkdir(folder, { recursive: true });
  for (const asset of catalog(edition).filter(a => a.kind === 'texture')) {
    const sourcePath = edition === 'java' ? `assets/minecraft/${asset.path}` : `resource_pack/${bedrockDisplayVariants[asset.path] ?? asset.path}`;
    const sourceUrl = edition === 'java' ? javaClient : `https://raw.githubusercontent.com/Mojang/bedrock-samples/${bedrockRevision}/${sourcePath}`;
    const png = edition === 'java' ? javaFiles[sourcePath] : await bytes(sourceUrl);
    if (!png || Buffer.from(png.subarray(0, 8)).toString('hex') !== '89504e470d0a1a0a') throw new Error(`Missing or non-PNG texture: ${sourcePath}`);
    const view = new DataView(png.buffer, png.byteOffset, png.byteLength);
    const fileName = asset.path.split('/').at(-1);
    await writeFile(new URL(fileName, folder), png);
    textures.push({ edition, gameVersion, path: asset.path, src: `/previews/${edition}-${gameVersion}/${fileName}`, width: view.getUint32(16), height: view.getUint32(20), sha256: createHash('sha256').update(png).digest('hex'), sourcePath, sourceUrl });
  }
}
await writeFile(new URL('src/catalog-previews.ts', root), `// Generated by scripts/sync-previews.mjs. Mojang assets retain their copyright.\nexport const previewCatalog = ${JSON.stringify({ sources, textures }, null, 2)} as const;\n`);
log(`Saved ${textures.length} source-pinned previews to ${fileURLToPath(new URL('public/previews/', root))}`);
